-- =========================================================
-- 送迎リクエストに「ターミナル」列を追加する
--
-- 空港へ向かう場合、ターミナル1／ターミナル2の
-- どちらへ向かうかをゲストが選択できるようにした。
-- 関西空港以外の目的地では NULL のまま（ターミナルの概念がないため）。
--
-- 値は '1' | '2' の文字列。将来ターミナルが増えても拡張しやすいよう
-- text 型とし、NULL 許容にする（既存の予約データとの後方互換のため）。
-- =========================================================

alter table transfer_requests
  add column if not exists terminal text;

comment on column transfer_requests.terminal is
  '空港へ向かう場合: ターミナル番号（''1'' | ''2''）。それ以外の目的地では NULL。';
